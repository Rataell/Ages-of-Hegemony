import { z } from 'zod';

/**
 * MatchReportV1 — the post-match report of an Alpha match.
 *
 * Rules of the format:
 *  - It is a pure, derived summary of the AUTHORITATIVE final state (plus the room's seat metadata). It never feeds back into the game.
 *  - Nothing private goes in: no access/join codes, tokens, e-mails, display names, `privateRng`. Seats are identified by seat id + civilization + human/bot kind.
 *  - A number is only present when a reliable source exists. Everything else is `null`/absent AND listed in `quality` as UNAVAILABLE or PARTIAL with the reason.
 *  - `schemaVersion` never changes meaning: a finished report is stored once and is never regenerated by a later patch (a new shape is a new schemaVersion).
 *  - Compact on purpose: per-round series are plain number arrays, the timeline is a curated list of milestones (not an event log).
 */
export const MATCH_REPORT_SCHEMA_VERSION = 1;
export const REPORT_RESOURCES = ['food', 'wood', 'stone', 'metal', 'wealth', 'knowledge', 'influence', 'culture'] as const;
export type ReportResource = (typeof REPORT_RESOURCES)[number];
/** The five pools of the legacy round ledger (wood, stone and metal are merged into `materials`; Cultura is not in it). */
export const LEDGER_POOLS = ['food', 'materials', 'wealth', 'knowledge', 'influence'] as const;

const N = z.number().int().min(0);
const Seat = z.string().min(1).max(32);
const ByResource = z.record(z.string(), N);
/** Net flows can be negative (a recurring effect that costs more than it gives in a round). */
const Flow = z.record(z.string(), z.number().int());
const Series = z.array(z.number());

/** OBSERVED: read straight from the final state / telemetry. CALCULATED: derived from observed values by a documented rule. PARTIAL: only part of the match or of the resources is covered. UNAVAILABLE: the data does not exist. */
export const ProvenanceSchema = z.enum(['OBSERVED', 'CALCULATED', 'PARTIAL', 'UNAVAILABLE']);
export type Provenance = z.infer<typeof ProvenanceSchema>;
export const QualityEntrySchema = z.strictObject({ field: z.string().max(80), status: ProvenanceSchema, note: z.string().max(300) });

export const SeatKindSchema = z.enum(['HUMAN', 'BOT', 'UNKNOWN']);

export const MatchReportV1Schema = z.strictObject({
  schemaVersion: z.literal(MATCH_REPORT_SCHEMA_VERSION),
  kind: z.literal('MatchReportV1'),
  /** Stable identity of the outcome: one report per definitive result. */
  reportId: z.string().min(8).max(120),
  /** LIVE: generated when the match finished. RECONSTRUCTED: rebuilt later from a finished snapshot. SIMULATION: emitted by a headless run. IMPORTED_RUN: converted from a recorded simulation run (partial). */
  origin: z.enum(['LIVE', 'RECONSTRUCTED', 'SIMULATION', 'IMPORTED_RUN']),
  generator: z.strictObject({ id: z.literal('match-report-1'), source: z.enum(['FINAL_STATE', 'RUN_ROWS']) }),

  match: z.strictObject({
    gameId: z.string().min(1).max(80),
    seed: N, worldPreset: z.string(), mapSize: z.string().nullable(), preset: z.string(),
    roundLimit: N, roundsPerEra: N, actionsPerRound: N, players: N,
    roundsPlayed: N,
    endReason: z.enum(['HEGEMONY', 'ROUND_LIMIT', 'OTHER']),
    /** ISO date of the conclusion when the caller knows it (the final state carries no clock). */
    finishedAt: z.string().nullable(),
    version: z.strictObject({ content: z.string().nullable(), rules: z.string(), engine: z.string(), app: z.string().nullable() }),
    /** Hash of everything that changes the economy/balance (balance tables, units, Hegemony requirements, calendar). Reports with different fingerprints must never be pooled silently. */
    economyFingerprint: z.string().min(6).max(24),
    /** Simulation grouping: same seed + same configuration = one sample, not many. */
    configKey: z.string().min(6).max(40),
  }),

  seats: z.array(z.strictObject({
    seat: Seat, civilization: z.string().nullable(), leader: z.string().nullable(),
    kind: SeatKindSchema, botPersona: z.string().nullable(), policy: z.string().nullable(),
  })).min(2).max(6),

  result: z.strictObject({
    winner: Seat,
    ranking: z.array(z.strictObject({
      seat: Seat, rank: N, prestige: N, researched: N, population: N, wealth: N,
      /** The first tie-break criterion that separated this seat from the one ranked right above it (null for rank 1). */
      decidedBy: z.enum(['prestige', 'research', 'population', 'wealth', 'initiative']).nullable(),
    })),
    hegemony: z.array(z.strictObject({
      seat: Seat, declaredPath: z.string().nullable(), declaredRound: N.nullable(), qualifiedSince: N.nullable(),
      /** Per path: requirements met out of the total, at the end of the match. */
      paths: z.array(z.strictObject({ path: z.string(), met: N, of: N })),
    })),
    /** Prestígio by source. milestones/ambitions/works/explored are CALCULATED from the final state; `other` is the remainder (cards, Ressonância, Ameaças, treaty penalties) and can be negative. */
    prestige: z.array(z.strictObject({ seat: Seat, total: N, milestones: N, ambitions: N, works: N, explored: N, other: z.number().int() })),
  }),

  civilizations: z.array(z.strictObject({
    seat: Seat,
    government: z.string().nullable(), reformEra: z.string().nullable(),
    leaderAbilityUses: N,
    cities: z.strictObject({
      atStart: N, founded: N, captured: N, lost: N, final: N, occupiedAtEnd: N,
      /** Total elevations (the Elevar action executed). */
      elevations: N.nullable(),
      maxLevel: N, meanLevel: z.number(), byLevel: z.array(N).length(7),
      /** First round at which the seat had a city of level 1..7 (null: never), from the round log. */
      firstRoundAtLevel: z.array(N.nullable()).length(7),
    }),
    population: z.strictObject({ firstRound: N.nullable(), final: N, series: Series }),
    districts: ByResource, buildings: ByResource,
    territory: N, regionsDiscovered: N,
    research: z.strictObject({ total: N, byDomain: ByResource, order: z.array(z.string()), heritages: N, milestonesReached: z.array(z.string()) }),
    resonance: z.strictObject({ cycles: N, repercussions: N.nullable() }),
    legacyWorks: z.array(z.strictObject({ workId: z.string(), cityId: z.string(), startedRound: N, completedRound: N.nullable(), stepsDone: N })),
  })),

  economy: z.strictObject({
    /** Round numbers the series below cover (the round log keeps the last 260 rows; longer matches lose their first rounds). */
    rounds: z.array(N),
    perSeat: z.array(z.strictObject({
      seat: Seat,
      /** Closing stock per round for the eight resources (reliable for every resource). */
      stock: z.record(z.string(), Series),
      atCapRounds: ByResource, emptyRounds: ByResource,
      /** Legacy five-pool flows summed over the covered rounds. wood/stone/metal are merged in `materials`; Cultura is absent. */
      ledger: z.strictObject({ produced: Flow, spent: Flow, lost: Flow, discarded: Flow }),
      /** Eight-resource flows summed over the covered rounds. Only instrumented simulation runs have them (null in live reports: the engine records no per-resource flows for wood/stone/metal/Cultura). */
      flows8: z.strictObject({ produced: Flow, consumed: Flow, discarded: Flow, spent: Flow }).nullable().default(null),
      shortage: z.strictObject({ foodRounds: N, upkeepRounds: N, overextensionRounds: N }),
      mood: z.strictObject({ mean: Series, min: Series, revoltRounds: N }),
      populationSeries: Series,
      cityCountSeries: Series, maxLevelSeries: Series, prestigeSeries: Series,
    })),
    /** Cumulative production by resource, ALL civilizations summed, PRODUCE output only (kit bonuses, trade and institutions are not in it). */
    globalProduction: ByResource.nullable(),
  }),

  actions: z.array(z.strictObject({
    seat: Seat,
    /** Orders committed per category over the covered rounds (committed, not necessarily succeeded). */
    ordersByCategory: ByResource,
    ordersCommitted: N, ordersAvailable: N, ordersUnused: N,
    /** Planned actions/orders the engine rejected at resolution (ACTION_FAILED / ORDER_FAILED events). */
    failedActions: N,
    /** Executed actions by resolution-event type (PRODUCTION, CONSTRUCTION, RECRUITMENT, RESEARCH, FOUNDATION, MOVEMENT, ...). */
    executed: ByResource,
  })),

  conflicts: z.strictObject({
    battles: z.strictObject({ pvp: N, againstThreats: N, byThreats: N }),
    perSeat: z.array(z.strictObject({
      seat: Seat,
      attacks: N, attackWins: N, attackLosses: N, defences: N, defenceWins: N,
      unitsLost: N, unitsDestroyed: N,
      assaultsSuffered: N, threatAttacks: N,
    })),
    warsDeclared: N, warsActiveAtEnd: z.array(z.tuple([Seat, Seat])),
    threats: z.strictObject({ spawned: N, attacks: N, campsDestroyed: N, lossesOfThreats: N, assaultEvents: N, pirateEvents: N }),
    diplomacy: z.strictObject({
      treaties: z.record(z.string(), N), tradeOffers: N, tradeAccepted: N, routesAtEnd: N,
      contactsBySeat: z.record(Seat, N),
    }),
  }),

  timeline: z.array(z.strictObject({ round: N, seat: Seat.nullable(), kind: z.string().max(40), text: z.string().max(200) })).max(160),

  coverage: z.strictObject({ roundsExpected: N, roundsRecorded: N, truncated: z.boolean() }),
  quality: z.array(QualityEntrySchema),
});
export type MatchReportV1 = z.infer<typeof MatchReportV1Schema>;

/** Flat, comparable table rows of a report (one per seat) used by the CSV export and by the Meta aggregator. */
export function matchReportRows(report: MatchReportV1): Record<string, string | number | null>[] {
  return report.seats.map(seat => {
    const rank = report.result.ranking.find(entry => entry.seat === seat.seat);
    const civ = report.civilizations.find(entry => entry.seat === seat.seat);
    const prestige = report.result.prestige.find(entry => entry.seat === seat.seat);
    const action = report.actions.find(entry => entry.seat === seat.seat);
    const fight = report.conflicts.perSeat.find(entry => entry.seat === seat.seat);
    const eco = report.economy.perSeat.find(entry => entry.seat === seat.seat);
    const last = <T,>(series: T[] | undefined): T | null => (series && series.length ? series[series.length - 1]! : null);
    return {
      gameId: report.match.gameId, seat: seat.seat, civilization: seat.civilization, leader: seat.leader, kind: seat.kind, policy: seat.policy ?? seat.botPersona,
      rank: rank?.rank ?? null, winner: report.result.winner === seat.seat ? 1 : 0, prestige: rank?.prestige ?? null, researched: rank?.researched ?? null,
      prestigeMilestones: prestige?.milestones ?? null, prestigeAmbitions: prestige?.ambitions ?? null, prestigeWorks: prestige?.works ?? null, prestigeExplored: prestige?.explored ?? null, prestigeOther: prestige?.other ?? null,
      government: civ?.government ?? null, cities: civ?.cities.final ?? null, maxLevel: civ?.cities.maxLevel ?? null, population: civ?.population.final ?? null,
      districts: civ ? Object.values(civ.districts).reduce((a, b) => a + b, 0) : null, buildings: civ ? Object.values(civ.buildings).reduce((a, b) => a + b, 0) : null,
      territory: civ?.territory ?? null, regions: civ?.regionsDiscovered ?? null, legacyWorksDone: civ ? civ.legacyWorks.filter(work => work.completedRound !== null).length : null,
      ordersCommitted: action?.ordersCommitted ?? null, ordersUnused: action?.ordersUnused ?? null, failedActions: action?.failedActions ?? null,
      attacks: fight?.attacks ?? null, attackWins: fight?.attackWins ?? null, assaultsSuffered: fight?.assaultsSuffered ?? null,
      foodShortageRounds: eco?.shortage.foodRounds ?? null, revoltRounds: eco?.mood.revoltRounds ?? null,
      finalWealth: last(eco?.stock.wealth), finalKnowledge: last(eco?.stock.knowledge), finalCulture: last(eco?.stock.culture),
      players: report.match.players, roundsPlayed: report.match.roundsPlayed, endReason: report.match.endReason, economyFingerprint: report.match.economyFingerprint,
    };
  });
}
const csvCell = (value: string | number | null): string => value === null ? '' : typeof value === 'number' ? String(value) : /[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
/** CSV of the per-seat comparison table (header + one row per seat). */
export function matchReportToCsv(report: MatchReportV1): string {
  const rows = matchReportRows(report), header = Object.keys(rows[0] ?? {});
  return [header.join(','), ...rows.map(row => header.map(key => csvCell(row[key] ?? null)).join(','))].join('\n') + '\n';
}

const RESOURCE_PT: Record<string, string> = { food: 'Alimento', wood: 'Madeira', stone: 'Pedra', metal: 'Metal', wealth: 'Riqueza', knowledge: 'Conhecimento', influence: 'Influência', culture: 'Cultura' };
const DECIDED_PT: Record<string, string> = { prestige: 'Prestígio', research: 'pesquisas', population: 'população', wealth: 'riqueza', initiative: 'ordem de iniciativa' };
const md = (rows: (string | number | null)[][], head: string[]): string => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(row => `| ${row.map(cell => cell ?? '–').join(' | ')} |`)].join('\n');
/** Plain-language summary of a report (the same facts the Crônica da Partida shows), for terminals, issues and exports. Seats are shown by id: the report holds no names. */
export function matchReportToMarkdown(report: MatchReportV1): string {
  const m = report.match, seatLabel = (seat: string) => { const s = report.seats.find(entry => entry.seat === seat); return `${seat}${s?.civilization ? ` (${s.civilization}${s.kind === 'BOT' ? ', bot' : ''})` : ''}`; };
  const lines = [
    `# Crônica da partida ${m.gameId}`, '',
    `${m.endReason === 'HEGEMONY' ? `Hegemonia consolidada na rodada ${m.roundsPlayed}` : `Maior Prestígio ao fim de ${m.roundsPlayed} rodadas`} · ${m.players} civilizações · semente ${m.seed} · mundo ${m.worldPreset}${m.mapSize ? `, mapa ${m.mapSize}` : ''} · economia ${m.economyFingerprint} · origem ${report.origin}.`, '',
    `**Vencedor: ${seatLabel(report.result.winner)}.**`, '',
    '## Ranking', md(report.result.ranking.map(r => [r.rank, seatLabel(r.seat), r.prestige, r.researched, r.population, r.wealth, r.decidedBy ? DECIDED_PT[r.decidedBy] ?? r.decidedBy : '–']), ['#', 'Civilização', 'Prestígio', 'Pesquisas', 'População', 'Riqueza', 'Desempate']), '',
    '## De onde veio o Prestígio', md(report.result.prestige.map(p => [seatLabel(p.seat), p.milestones, p.ambitions, p.works, p.explored, p.other, p.total]), ['Civilização', 'Marcos ★', 'Ambições', 'Obras', 'Regiões', 'Outras fontes', 'Total']), '',
    '## Desenvolvimento', md(report.civilizations.map(c => [seatLabel(c.seat), c.government, `${c.cities.final} (+${c.cities.founded} fundadas)`, `N${c.cities.maxLevel}`, c.population.final, Object.values(c.districts).reduce((a, b) => a + b, 0), Object.values(c.buildings).reduce((a, b) => a + b, 0), c.research.total, c.territory, c.regionsDiscovered, c.legacyWorks.filter(w => w.completedRound !== null).length]), ['Civilização', 'Governo', 'Cidades', 'Nível', 'População', 'Distritos', 'Edifícios', 'Pesquisas', 'Território', 'Regiões', 'Obras']), '',
    '## Economia', md(report.economy.perSeat.map(e => [seatLabel(e.seat), e.shortage.foodRounds, e.shortage.upkeepRounds, e.mood.revoltRounds, ...['food', 'wood', 'stone', 'metal', 'wealth', 'knowledge', 'influence', 'culture'].map(r => `${e.stock[r]?.at(-1) ?? '–'} (${e.emptyRounds[r] ?? 0} vazio)`)]), ['Civilização', 'Rodadas de fome', 'Manutenção não paga', 'Rodadas de Revolta', ...Object.values(RESOURCE_PT).map(name => `${name} final`)]), '',
    '## Conflitos e Ordens', md(report.conflicts.perSeat.map(s => { const a = report.actions.find(x => x.seat === s.seat); return [seatLabel(s.seat), s.attacks, s.attackWins, s.defences, s.unitsLost, s.assaultsSuffered, a?.ordersCommitted ?? '–', a?.ordersUnused ?? '–', a?.failedActions ?? '–']; }), ['Civilização', 'Ataques', 'Vitórias', 'Defesas', 'Peças perdidas', 'Assaltos sofridos', 'Ordens usadas', 'Ordens ociosas', 'Ações recusadas']), '',
    `${report.conflicts.battles.pvp} batalha(s) entre civilizações · ${report.conflicts.battles.againstThreats} ataque(s) a Ameaças · ${report.conflicts.battles.byThreats} assalto(s) das Ameaças · ${report.conflicts.warsDeclared} guerra(s) declarada(s).`, '',
    '## Linha do tempo', ...report.timeline.map(t => `- Rodada ${t.round}${t.seat ? ` · ${t.seat}` : ''}: ${t.text}`), '',
    '## O que este relatório não sabe', ...report.quality.filter(q => q.status !== 'OBSERVED').map(q => `- **${q.status}** · ${q.field}: ${q.note}`), '',
  ];
  return lines.join('\n');
}
