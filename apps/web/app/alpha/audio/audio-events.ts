/** Semantic audio events. UI code names an event; it never knows a sound parameter or a path. */
export const SFX_EVENTS = [
  'UI_SELECT', 'ORDER_PLANNED', 'ORDER_RESOLVED', 'PLAN_CONFIRMED', 'UNIT_MOVED', 'REGION_REVEALED', 'CITY_FOUNDED',
  'BUILD_DONE', 'RESEARCH_DONE', 'RESONANCE_FILLED', 'REPERCUSSION', 'BATTLE_START', 'DICE_ROLL',
  'DICE_RESULT_IMPACT', 'DICE_RESULT_GUARD', 'DICE_RESULT_MANEUVER', 'DICE_RESULT_COMMAND', 'DICE_RESULT_EMPTY',
  'HIT', 'GUARD_BLOCK', 'UNIT_LOST', 'RETREAT', 'CITY_CAPTURED', 'CAMP_SPAWNED', 'RAID_ACTIVE', 'PIRATE_ACTIVE',
  'WORLD_PULSE', 'ENCOUNTER', 'WORLD_EVENT', 'ERA_CHANGED', 'REACTION_RECEIVED', 'PLAYER_JOINED', 'PLAYER_RECONNECTED',
] as const;
export type AudioEvent = (typeof SFX_EVENTS)[number];

/** Higher wins. ERA > COMBAT > REPERCUSSION > WORLD_EVENT > BUILD > MOVE > UI. */
export const PRIORITY = { UI: 1, MOVE: 2, BUILD: 3, WORLD_EVENT: 4, REPERCUSSION: 5, COMBAT: 6, ERA: 7 } as const;
export type PriorityClass = keyof typeof PRIORITY;

export type EventPolicy = { priority: PriorityClass; cooldownMs: number; durationMs: number };
const p = (priority: PriorityClass, cooldownMs: number, durationMs: number): EventPolicy => ({ priority, cooldownMs, durationMs });

